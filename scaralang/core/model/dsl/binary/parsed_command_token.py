@dataclass(slots=True, frozen=True)
class ParsedCommandToken:
    '''
        Immutable data model representing parsed command token and arguments.

        It defines:

            :attributes:
                | cmd_name - Normalized primary command identifier name.
                | arg - Primary argument string if present.
                | clean - Uppercase stripped raw command string.
                | parts - All whitespace-separated command tokens.
    '''

    cmd_name: str
    arg: str
    clean: str
    parts: tuple[str, ...] = ()
