__status__ = 'Updated'


@dataclass(slots=True, frozen=True, kw_only=True)
class ReplDispatchResult:
    '''
        Immutable data model recording the outcome of a REPL command dispatch.

        It defines:

            :attributes:
                | is_exit - True if the session termination command was requested.
                | is_handled - True if a built-in session command was executed.
                | message - Informational or diagnostic message from the dispatch.
    '''

    is_exit: bool
    is_handled: bool
    message: str
